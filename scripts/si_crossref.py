"""Generate the SI's front cross-reference table: every headline quantity in the
main text, the SI section that derives it, and the results file that produced
it.

WHY THIS IS GENERATED. The advisor's 2026-09-05 letter, point 4.6: a referee
judges an SI by whether it can be walked, and this SI's sections already say
which main-text section each supports, but nothing anywhere says which file a
given number came out of. Writing that mapping by hand would produce a table
that is right on the day it is written. So each row here names a file AND a
path inside it, and the script refuses to emit the table unless every path
resolves and every quoted value still matches. A row that has gone stale fails
the build instead of misleading a referee.

WHAT A ROW IS.

    (main-text quantity, main-text §, SI §, results file, path, expected)

`path` is dotted, with list indices in brackets, and `expected` may be None
when the row points at a file rather than at a single number. Tolerance is
relative and deliberately loose at 2e-4, because the table prints rounded
values and the point of the check is provenance, not a fifth decimal place.

    python scripts/si_crossref.py            # rewrite the block in the SI
    python scripts/si_crossref.py --check    # verify only, exit 1 on drift
"""
