TOL = 2e-4


def resolve(obj, path):
    """Walk a dotted path with bracketed list indices. Keys may contain dots
    only if they contain no '.', which is why the split is on '.' and the
    pipe-delimited cell keys survive: they hold no dots."""
    cur = obj
    # {...} protects a key that itself contains a dot, which p39's inversion
    # keys do: they are the beta values, "0.95" and "0.99".
    parts, buf, depth = [], "", 0
    for ch in path:
        if ch == "{":
            depth += 1
            continue
        if ch == "}":
            depth -= 1
            continue
        if ch == "." and depth == 0:
            parts.append(buf)
            buf = ""
            continue
        buf += ch
    parts.append(buf)
    for part in parts:
        m = re.match(r"^([^\[]*)((?:\[\d+\])*)$", part)
        key, idx = m.group(1), m.group(2)
        if key:
            if not isinstance(cur, dict) or key not in cur:
                raise KeyError(f"{path}: no key {key!r}")
            cur = cur[key]
        for i in re.findall(r"\[(\d+)\]", idx):
            cur = cur[int(i)]
    return cur


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    cache, bad, lines = {}, [], []
    for label, sec, si, fname, path, expected in ROWS:
        if fname not in cache:
            p = f"{ROOT}/eda/{fname}"
            if not os.path.exists(p):
                bad.append(f"{label}: {fname} does not exist")
                continue
            with open(p) as fh:
                cache[fname] = json.load(fh)
        try:
            got = resolve(cache[fname], path)
        except (KeyError, IndexError, TypeError) as e:
            bad.append(f"{label}: {e}")
            continue
        if expected is not None:
            if not isinstance(got, (int, float)) or isinstance(got, bool):
                bad.append(f"{label}: {path} is {type(got).__name__}, not a number")
                continue
            if abs(got - expected) > abs(expected) * TOL + 1e-12:
                bad.append(f"{label}: {path} is {got!r}, table says {expected!r}")
                continue
        lines.append(f"| {label} | §{sec} | {si} | `{fname}` |")

    if bad:
        print("cross-reference rows that no longer resolve:", file=sys.stderr)
        for b in bad:
            print(f"  {b}", file=sys.stderr)
        return 1

    table = "\n".join([
        BEGIN,
        "",
        "**Table S0. Where each headline number comes from.** One row per "
        "quantity the main text states, the section of this document that "
        "derives it, and the file under `eda/` that produced it. The table is "
        "generated by `scripts/si_crossref.py`, which reads each value back "
        "out of the named file and fails rather than print a row that has "
        "gone stale.",
        "",
        "| Quantity in the main text | Main text | This document | Produced by |",
        # PROPORTIONAL DASHES, NOT FOUR EQUAL RUNS. pandoc reads a pipe
        # table's column widths off the separator row, so "|---|---|---|---|"
        # gives each column a quarter of the text block and a 25-character
        # monospace filename then runs 18pt past its cell. The widths below
        # are the ones that fit the longest cell in each column.
        "|--------------------------------------|------|------|--------------------------------|",
        *lines,
        "",
        END,
    ])

    with open(SI, encoding="utf-8") as fh:
        s = fh.read()
    if BEGIN in s and END in s:
        s2 = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), table, s,
                    flags=re.S)
    else:
        anchor = "## 1. Extended related work"
        assert anchor in s, "the SI no longer opens with §1, so there is no "\
                            "unambiguous place to put the table"
        s2 = s.replace(anchor, table + "\n\n" + anchor, 1)

    if args.check:
        ok = s2 == s
        print(f"{len(lines)} rows verified; SI block "
              f"{'is current' if ok else 'is STALE, re-run without --check'}")
        return 0 if ok else 1

    with open(SI, "w", encoding="utf-8") as fh:
        fh.write(s2)
    print(f"{len(lines)} rows verified and written into {SI}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
